import { ArrowDownRight, ArrowUpRight, FlaskConical } from "lucide-react";
import { attackMeta, PRIORITY_COLOR, riskColor, SEVERITY_META, STATUS_META } from "../lib/meta";

export function SeverityPill({ severity }) {
  const m = SEVERITY_META[severity] || { label: severity, cls: "" };
  return (
    <span className={`pill ${m.cls}`}>
      <span className="pdot" aria-hidden="true" />
      {m.label}
    </span>
  );
}

export function StatusPill({ status }) {
  const m = STATUS_META[status] || { label: status, cls: "" };
  return <span className={`pill ${m.cls}`}>{m.label}</span>;
}

export function PriorityTag({ priority }) {
  if (!priority) return <span className="muted">—</span>;
  return (
    <span className="num" style={{ fontWeight: 600, display: "inline-flex", alignItems: "center", gap: 6 }}>
      <span
        aria-hidden="true"
        style={{ width: 8, height: 8, borderRadius: 2, background: PRIORITY_COLOR[priority] }}
      />
      {priority}
    </span>
  );
}

export function OriginPill({ origin, compact }) {
  if (!origin || origin === "ingest") return null;
  const label = origin === "seed" ? "Demo data" : "Simulated";
  if (compact) {
    return (
      <span className="origin-dot" title={`${label}: generated, not real network traffic`}>
        <FlaskConical size={14} aria-label={label} />
      </span>
    );
  }
  return (
    <span className="pill pill-outline" title="Generated by the Threat Simulator, not real network traffic">
      <FlaskConical size={11} aria-hidden="true" />
      {origin === "seed" ? "Demo data" : "Simulated"}
    </span>
  );
}

export function AttackAvatar({ type, size }) {
  const { Icon } = attackMeta(type);
  const cls = size === "sm" ? "atk-avatar-sm" : size === "lg" ? "atk-avatar-lg" : "";
  const px = size === "sm" ? 13 : size === "lg" ? 22 : 16;
  return (
    <span className={`atk-avatar atk-${type} ${cls}`} aria-hidden="true">
      <Icon size={px} strokeWidth={2} />
    </span>
  );
}

export function AttackCell({ type, sub }) {
  const m = attackMeta(type);
  return (
    <div className="cell-main">
      <AttackAvatar type={type} />
      <div style={{ minWidth: 0 }}>
        <div className="cell-title">{m.label}</div>
        {sub && <div className="cell-sub">{sub}</div>}
      </div>
    </div>
  );
}

export function RiskBar({ score }) {
  const value = score ?? 0;
  return (
    <span className="riskbar">
      <span className="riskbar-track" aria-hidden="true">
        <span
          className="riskbar-fill"
          style={{ width: `${Math.round(value * 100)}%`, background: riskColor(value) }}
        />
      </span>
      <span className="num" style={{ fontSize: 13 }}>
        {value.toFixed(2)}
      </span>
    </span>
  );
}

/**
 * Change chip. `polarity` says which direction is good for this metric:
 * "up-bad" for threat counts (more alerts is worse), "up-good" for precision.
 */
export function Delta({ value, unit = "%", polarity = "up-bad", digits = 1 }) {
  if (value == null) {
    return (
      <span className="delta" title="No comparison period yet">
        n/a
      </span>
    );
  }
  const rounded = Number(value.toFixed(digits));
  const dir = rounded > 0 ? "up" : rounded < 0 ? "down" : "flat";
  let tone = "";
  if (dir !== "flat") {
    const good = polarity === "up-good" ? dir === "up" : dir === "down";
    tone = good ? "delta-good" : "delta-bad";
  }
  const Arrow = dir === "down" ? ArrowDownRight : ArrowUpRight;
  return (
    <span className={`delta ${tone}`}>
      {dir !== "flat" && <Arrow size={12} strokeWidth={2.4} aria-hidden="true" />}
      {dir === "up" ? "+" : ""}
      {Math.abs(rounded) === 0 ? "0" : rounded}
      {unit}
      <span className="sr-only">{dir === "up" ? " increase" : dir === "down" ? " decrease" : " no change"}</span>
    </span>
  );
}
